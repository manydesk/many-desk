/// Mac ↔ PC: swap Cmd and Ctrl so shortcuts keep their meaning on the other side.
pub fn swap_mods(code: &'static str) -> &'static str {
    match code {
        "MetaLeft" => "ControlLeft",
        "MetaRight" => "ControlRight",
        "ControlLeft" => "MetaLeft",
        "ControlRight" => "MetaRight",
        c => c,
    }
}
